#!/usr/bin/env node
// Writes the texts every app shows from their one source, shared/texts.json:
//
//   IslandStrings.js                              the Omarchy plugin's STRINGS
//   desktop/crates/island-core/src/texts_gen.rs   the desktop apps' Texts
//
// Each entry: { "id", "rust"?, "os": ["omarchy"|"windows"|"macos"...], "note"?,
// "en", "es", "pt" }. `id` is the plugin's key and stays as the QML asks for
// it; `rust` is the desktop field (the id in snake_case unless given); `note`
// becomes the field's doc comment. Placeholders are `{0}`, `{1}`: the plugin
// gets `%1`, `%2` and the desktop `{}`, so on the desktop they must come in
// order. An entry belongs to the plugin if `os` has "omarchy" and to the
// desktop apps if it has "windows" or "macos".
//
// `node scripts/gen-shared.mjs` writes both files; `--check` writes nothing
// and fails when they are not what the source says (CI runs it as a test).

import { readFileSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath, pathToFileURL } from "node:url"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
export const SOURCE = path.join(root, "shared", "texts.json")
export const JS_OUT = path.join(root, "IslandStrings.js")
export const RUST_OUT = path.join(root, "desktop", "crates", "island-core", "src", "texts_gen.rs")

export const LANGS = ["en", "es", "pt"]
const OSES = ["omarchy", "windows", "macos"]
const RUST_KEYWORDS = new Set(
  "as break const continue crate else enum extern false fn for if impl in let loop match mod move mut pub ref return self Self static struct super trait true type unsafe use where while async await dyn abstract become box do final macro override priv typeof unsized virtual yield try gen".split(" "),
)
const HEADER = "Generated by scripts/gen-shared.mjs from shared/texts.json: do not edit."

export const forPlugin = (e) => e.os.includes("omarchy")
export const forDesktop = (e) => e.os.includes("windows") || e.os.includes("macos")
export const snake = (id) => id.replace(/[A-Z]/g, (c) => "_" + c.toLowerCase())
export const field = (e) => e.rust ?? snake(e.id)

// The placeholders of `text`, in the order they appear.
export const placeholders = (text) => [...text.matchAll(/\{(\d+)\}/g)].map((m) => Number(m[1]))

export function readSource(file = SOURCE) {
  return JSON.parse(readFileSync(file, "utf8"))
}

// Throws on anything the outputs could not state faithfully.
export function validate(entries) {
  if (!Array.isArray(entries)) throw new Error("texts.json: an array of entries")
  const ids = new Set()
  const fields = new Set()
  for (const e of entries) {
    const id = e?.id
    const where = `texts.json «${id}»`
    if (typeof id !== "string" || !id) throw new Error("texts.json: an entry without id")
    if (ids.has(id)) throw new Error(`${where}: id twice`)
    ids.add(id)
    if (!Array.isArray(e.os) || !e.os.length || e.os.some((o) => !OSES.includes(o))) {
      throw new Error(`${where}: os is a list of ${OSES.join(", ")}`)
    }
    for (const l of LANGS) {
      if (typeof e[l] !== "string" || !e[l].trim()) throw new Error(`${where}: no ${l}`)
      // JSON and Rust escape these differently: keep them out.
      if (/[\u0000-\u0008\u000b-\u001f\u007f]|[\ud800-\udfff]/.test(e[l])) {
        throw new Error(`${where}: ${l} has a control character`)
      }
    }
    if (e.note !== undefined && (typeof e.note !== "string" || /[\r\n]/.test(e.note))) {
      throw new Error(`${where}: note is one line`)
    }
    const sets = LANGS.map((l) => placeholders(e[l]).slice().sort((a, b) => a - b).join(","))
    if (new Set(sets).size !== 1) throw new Error(`${where}: the languages disagree on the placeholders`)
    if (forPlugin(e) && LANGS.some((l) => placeholders(e[l]).some((n) => n > 0))) {
      throw new Error(`${where}: the plugin takes one argument, {0}`)
    }
    if (forDesktop(e)) {
      const f = field(e)
      if (!/^[a-z][a-z0-9_]*$/.test(f) || RUST_KEYWORDS.has(f)) throw new Error(`${where}: «${f}» is no Rust field`)
      if (fields.has(f)) throw new Error(`${where}: Rust field «${f}» twice`)
      fields.add(f)
      for (const l of LANGS) {
        const order = placeholders(e[l])
        if (order.some((n, i) => n !== i)) throw new Error(`${where}: ${l} has its placeholders out of order`)
        if (/[{}]/.test(e[l].replace(/\{\d+\}/g, ""))) throw new Error(`${where}: ${l} has a stray brace`)
      }
    }
  }
}

const jsText = (text) => JSON.stringify(text.replace(/\{(\d+)\}/g, (_, n) => `%${Number(n) + 1}`))
const rustText = (text) => JSON.stringify(text.replace(/\{\d+\}/g, "{}"))

export function renderJs(entries) {
  const list = entries.filter(forPlugin)
  const out = [".pragma library", "", `// ${HEADER}`, "", "var STRINGS = {"]
  LANGS.forEach((l, i) => {
    out.push(`  ${l}: {`)
    list.forEach((e, j) => out.push(`    ${JSON.stringify(e.id)}: ${jsText(e[l])}${j < list.length - 1 ? "," : ""}`))
    out.push(i < LANGS.length - 1 ? "  }," : "  }")
  })
  out.push("}", "")
  return out.join("\n")
}

export function renderRust(entries) {
  const list = entries.filter(forDesktop)
  const out = [`// ${HEADER}`, "", "#[derive(Debug, PartialEq, Eq)]", "pub struct Texts {"]
  for (const e of list) {
    if (e.note) out.push(`    /// ${e.note}`)
    out.push(`    pub ${field(e)}: &'static str,`)
  }
  out.push("}", "")
  for (const l of LANGS) {
    out.push(`pub const ${l.toUpperCase()}: Texts = Texts {`)
    for (const e of list) out.push(`    ${field(e)}: ${rustText(e[l])},`)
    out.push("};", "")
  }
  out.push("/// Every text of `t`, in the order of the struct.", `pub fn all(t: &Texts) -> [&'static str; ${list.length}] {`, "    [")
  for (const e of list) out.push(`        t.${field(e)},`)
  out.push("    ]", "}", "")
  return out.join("\n")
}

export function render(entries) {
  validate(entries)
  return { js: renderJs(entries), rust: renderRust(entries) }
}

const lf = (s) => s.replace(/\r\n/g, "\n")

// Whether `file` says what was rendered (line endings aside: a checkout may
// turn them into CRLF).
export function upToDate(file, text) {
  try {
    return lf(readFileSync(file, "utf8")) === text
  } catch {
    return false
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const { js, rust } = render(readSource())
  const outputs = [[JS_OUT, js], [RUST_OUT, rust]]
  if (process.argv.includes("--check")) {
    const stale = outputs.filter(([file, text]) => !upToDate(file, text)).map(([file]) => path.relative(root, file))
    if (stale.length) {
      console.error(`Out of date: ${stale.join(", ")}. Run: node scripts/gen-shared.mjs`)
      process.exit(1)
    }
    console.log("shared texts: up to date")
  } else {
    for (const [file, text] of outputs) writeFileSync(file, text, "utf8")
    console.log(`wrote ${path.relative(root, JS_OUT)} and ${path.relative(root, RUST_OUT)}`)
  }
}
